# Вводим длину первого и второго катетов
a = float(input("Введите первый катет: "))
b = float(input("Введите второй катет: "))

# Вычисляем гипотенузу по теореме Пифагора
c = (a ** 2 + b ** 2) ** 0.5

# Вычисляем площадь прямоугольного треугольника
S = (a * b) / 2

# Выводим результаты на экран
print("Гипотенуза:", round(c, 2))
print("Площадь треугольника:", round(S, 2))